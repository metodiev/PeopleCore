const dictionaries: Record<Language, Messages> = { bg, en };

type Leaves<T> = {
  [K in keyof T & string]: T[K] extends string ? K : `${K}.${Leaves<T[K]>}`;
}[keyof T & string];

export type MessageKey = Leaves<Messages>;

function lookup(messages: Messages, path: string): string {
  const parts = path.split('.');
  let current: unknown = messages;
  for (const part of parts) {
    if (typeof current !== 'object' || current === null) return path;
    current = (current as Record<string, unknown>)[part];
  }
  return typeof current === 'string' ? current : path;
}

function interpolate(template: string, vars?: Record<string, string | number>): string {
  if (!vars) return template;
  return template.replace(/\{\{(\w+)\}\}/g, (match, key: string) => {
    const value = vars[key];
    return value === undefined ? match : String(value);
  });
}

interface I18nState {
  language: Language;
  hydrated: boolean;
  setLanguage: (language: Language) => void;
  hydrate: () => Promise<void>;
}

export const useI18nStore = create<I18nState>((set) => ({
  language: 'bg',
  hydrated: false,
  setLanguage: (language) => {
    set({ language });
    void writeSecure(StorageKeys.language, language);
  },
  hydrate: async () => {
    if (useI18nStore.getState().hydrated) return;
    const stored = await readSecure(StorageKeys.language);
    set({ language: stored === 'en' ? 'en' : 'bg', hydrated: true });
  },
}));

/** Imperative translate for non-component code (alerts, notifications). */
export function translate(language: Language, key: MessageKey, vars?: Record<string, string | number>): string {
  return interpolate(lookup(dictionaries[language], key), vars);
}

export function useI18n(): {
  t: (key: MessageKey, vars?: Record<string, string | number>) => string;
  language: Language;
  setLanguage: (language: Language) => void;
} {
  const language = useI18nStore((state) => state.language);
  const setLanguage = useI18nStore((state) => state.setLanguage);

  const t = useCallback(
    (key: MessageKey, vars?: Record<string, string | number>) =>
      interpolate(lookup(dictionaries[language], key), vars),
    [language],
  );

  return { t, language, setLanguage };
}
